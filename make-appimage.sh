#!/bin/sh

set -eu

ARCH=$(uname -m)
export ARCH
export OUTPATH=./dist
export ADD_HOOKS="self-updater.hook"
export UPINFO="gh-releases-zsync|${GITHUB_REPOSITORY%/*}|${GITHUB_REPOSITORY#*/}|latest|*$ARCH.AppImage.zsync"
export ICON=/usr/share/icons/hicolor/scalable/apps/com.strlen.TreeSheets.svg
export DESKTOP=/usr/share/applications/com.strlen.TreeSheets.desktop

# Deploy dependencies
quick-sharun \
	/usr/bin/TreeSheets   \
	/usr/share/TreeSheets \
	/usr/share/doc/TreeSheets # is this one needed?

# Additional changes can be done in between here

# Turn AppDir into AppImage
quick-sharun --make-appimage

# Test the app for 12 seconds, if the test fails due to the app
# having issues running in the CI use --simple-test instead
quick-sharun --test ./dist/*.AppImage
